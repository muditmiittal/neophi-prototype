import path from 'node:path';
import { chromium } from 'playwright-core';
import { findChromium } from './browser.mjs';
const base = `http://localhost:${process.env.PORT || 4173}`;
const out = (n) => path.resolve('..', 'deck-assets', `${n}.jpg`);
const b = await chromium.launch({ executablePath: findChromium() });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block', reducedMotion: 'reduce' });
const p = await ctx.newPage();
await p.goto(`${base}/app`, { waitUntil: 'networkidle' });
await p.getByRole('button', { name: /Load the full sample library/ }).click();
await p.waitForTimeout(700);
await p.screenshot({ path: out('library'), type: 'jpeg', quality: 80 });
await p.goto(`${base}/app/m/s-dance`, { waitUntil: 'networkidle' }); await p.waitForTimeout(500);
await p.screenshot({ path: out('memory'), type: 'jpeg', quality: 80, clip: { x: 0, y: 90, width: 1440, height: 1000 } });
await p.goto(`${base}/app/projects`, { waitUntil: 'networkidle' }); await p.waitForTimeout(500);
await p.screenshot({ path: out('projects'), type: 'jpeg', quality: 80 });
await p.goto(`${base}/`, { waitUntil: 'networkidle' }); await p.waitForTimeout(1500);
await p.screenshot({ path: out('home'), type: 'jpeg', quality: 80 });
await b.close();
