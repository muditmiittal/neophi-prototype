// Seeds the demo, then checks the command palette, drag to a category and the card morph.
import path from 'node:path';
import { chromium } from 'playwright-core';
import { findChromium } from './browser.mjs';
const base = `http://localhost:${process.env.PORT || 4173}`;
const b = await chromium.launch({ executablePath: findChromium() });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block' });
const p = await ctx.newPage(); const errs = [];
p.on('pageerror', (e) => errs.push(String(e))); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(`${base}/app`, { waitUntil: 'networkidle' });
await p.getByRole('button', { name: /Load the full sample library/ }).click(); await p.waitForTimeout(600);
await p.keyboard.press('Control+k'); await p.waitForTimeout(300);
await p.keyboard.type('red shirt'); await p.waitForTimeout(500);
const opts = await p.locator('.palette-list li').allTextContents();
console.log('palette results:', opts.length, '| first:', (opts[0] || '').slice(0, 60));
await p.screenshot({ path: path.resolve('SCREENSHOTS', 'palette-1440.png') });
await p.keyboard.press('Enter'); await p.waitForTimeout(900);
console.log('after Enter url:', new URL(p.url()).pathname);
await p.goto(`${base}/app`, { waitUntil: 'networkidle' }); await p.waitForTimeout(500);
const card = p.locator('.mcard').first(); const title = (await card.locator('h3').textContent())?.trim();
const tab = p.locator('.tab', { hasText: 'Goa in January' }).first();
const before = await tab.locator('.tnum').textContent();
await card.dragTo(tab); await p.waitForTimeout(500);
const after = await tab.locator('.tnum').textContent();
console.log('drag', JSON.stringify(title), 'to Goa in January: count', before, '->', after);
await p.locator('.mcard-pic').nth(2).hover(); await p.waitForTimeout(400);
await p.screenshot({ path: path.resolve('SCREENSHOTS', 'spotlight-1440.png') });
await p.locator('.mcard-pic').nth(2).click(); await p.waitForTimeout(900);
console.log('morph open url:', new URL(p.url()).pathname, '| frame visible:', await p.locator('#frame').isVisible());
console.log(errs.length ? 'errors:\n' + errs.join('\n') : 'no console errors');
await b.close();
